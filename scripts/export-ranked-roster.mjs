// Export the actual guest matching model, not a second approximate matcher.
// Run: node scripts/export-ranked-roster.mjs [--check]
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const html = fs.readFileSync(new URL('index.html', root), 'utf8');
const block = id => html.match(new RegExp(`<script id="${id}">([\\s\\S]*?)<\\/script>`))?.[1] ?? (() => { throw Error(`Missing ${id}`); })();
const ctx = vm.createContext({});
vm.runInContext(block('roster-data') + block('game-model'), ctx);
const { players, game } = vm.runInContext('({players: PLAYERS, game: CareerGame})', ctx);
const competitions = ['all', ...game.COMPETITION_IDS];
const candidates = game.candidates.map(p => ({ id: p.id, label: p.name }));
const byName = new Map(game.candidates.map(p => [p.name, p]));
const roster = players.map(p => ({ id: p.id, country: p.country, position: p.position }));
const memberships = players.flatMap(p => ['all', ...p.competitions].map(competition => ({player_id:p.id, competition})));
const rivals = players.flatMap(p => game.eligibleRivals(p).map(name => {
  const q = byName.get(name);
  assert(q && q.id !== p.id);
  assert.notDeepEqual(p.clubs.map(c => c.name), q.clubs.map(c => c.name));
  return {player_id:p.id, candidate_id:q.id, tier:game.matchTier(p,q), similarity:game.similarity(p,q), competitions:q.competitions};
}));
for (const p of players) assert(rivals.filter(r => r.player_id === p.id && r.tier === 0).length >= 4, p.id);
assert.equal(new Set(candidates.map(p=>p.id)).size, candidates.length);
const quoted = value => "'" + JSON.stringify(value).replaceAll("'", "''") + "'::jsonb";
const insert = (table, data, columns) => `insert into ranked_private.${table} select * from jsonb_to_recordset(${quoted(data)}) as x(${columns});\n`;
const sql = '-- Generated by scripts/export-ranked-roster.mjs from roster-data + game-model.\n-- Frozen ruleset v1: do not overwrite after production play; use a reviewed migration.\n' +
  insert('competitions', competitions.map(id => ({id})), 'id text') +
  insert('candidates', candidates, 'id text, label text') +
  insert('players', roster, 'id text, country text, position text') +
  insert('memberships', memberships, 'player_id text, competition text') +
  insert('rivals', rivals, 'player_id text, candidate_id text, tier integer, similarity double precision, competitions text[]');
const path = new URL('supabase/migrations/202609130002_ranked_roster.sql', root);
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(path, 'utf8'), sql, 'Ranked roster is stale; regenerate and review');
else { fs.mkdirSync(new URL('supabase/migrations/', root), {recursive:true}); fs.writeFileSync(path, sql); }
console.log(JSON.stringify({players:roster.length,candidates:candidates.length,rivals:rivals.length,memberships:memberships.length,competitions:competitions.length,check:process.argv.includes('--check')}));
